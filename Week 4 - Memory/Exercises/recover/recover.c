// This program recovers lost image files from a memory card
// It iterates through each block of memory conatining 512 bytes
// The header for JPEG file type indicates the beginning of a new file(image)
// The files continue dowmloading and writing into each [512] block 
// until it reachers a new header
// The program skips over blocks which do not contain headers (garbage files)

#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>

#define BLOCK_SIZE 512

int main(int argc, char *argv[])
{
    // Accept a single command-line argument
    if (argc != 2)
    {
        printf("Usage: ./recover FILE\n");
        return 1;
    }

    // Open the memory card
    FILE *card = fopen(argv[1], "rb");
    // Check to be sure the file was opened properly
    if (card == NULL)
    {
        return 2;
    }

    // Create a buffer for a block of data
    uint8_t buffer[BLOCK_SIZE];
    // Declare variables
    FILE *img = NULL;
    int count = 0;
    char file_name[8];

    // While there's still data left to read from the memory card
    while (fread(buffer, 1, BLOCK_SIZE, card) == BLOCK_SIZE)
    {
        // Check if header files match JPEG type
        if (buffer[0] == 0xff && buffer[1] == 0xd8 && buffer[2] == 0xff &&
            (buffer[3] & 0xf0) == 0xe0)
        {
            if (img != NULL)
            {
                fclose(img);
            }

            // Create JPEGs from the data
            // Filenames: ###.jpg, starting at 000.jpg
            sprintf(file_name, "%03i.jpg", count);
            img = fopen(file_name, "wb");
            if (img == NULL)
            {
                fclose(card);
                return 3;
            }
            count++;
        }

        // Writing buffer if a JPEG is open
        if (img != NULL)
        {
            fwrite(buffer, 1, BLOCK_SIZE, img);
        }
    }

    if (img != NULL)
    {
        fclose(img);
    }

    fclose(card);
    return 0;
}


