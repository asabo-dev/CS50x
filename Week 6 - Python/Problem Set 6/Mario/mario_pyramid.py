# Prints a right-aligned half pyramid
# CS50 mario.py Problem Set 6 solution.

from cs50 import get_int


def main():
    # Prompt user for height of pyramid
    while True:
        n = get_int("Height: ")

        # Ensure that input ranges between 1 and 8 inclusive
        if 1 <= n <= 8:
            break

    # Print each row of the pyramid
    for i in range(n):
        # Decrease spaces and increase bricks with each row
        print_row((n - i) - 1, i + 1)


def print_row(spaces, bricks):
    """Print one row of the pyramid"""

    for _ in range(spaces):
        print(" ", end="")

    for _ in range(bricks):
        print("#", end="")

    print()


if __name__ == "__main__":
    main()


