// Unloads dictionary from memory, returning true if successful, else false
bool unload(void)
{
    // Iterate over each bucket in the hash table
    for (int i = 0; i < N; i++)
    {
        // Point cursor to the first node in the current bucket
        node *cursor = table[i];
        // Traverse the linked list until the end
        while (cursor != NULL)
        {
            // Save the address of the next node before freeing the current node
            node *tmp = cursor->next;
            free(cursor);
            // Move cursor to the next node using the saved address
            cursor = tmp;
        }
    }
    return true;
}


