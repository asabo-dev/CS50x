// Hashes a word to a number (bucket index) in the hash table
unsigned int hash(const char *word)
{
    // Initialise a variable to store the sum of ASCII values
    unsigned int sum = 0;

    // Initialise character position counter
    int i = 0;

    // Loop through each character until the end of the string
    while (word[i] != '\0')
    {
        // Convert character to uppercase, multiply its ASCII value
        // by its position, and add the result to the running sum
        sum += (toupper(word[i]) * (i + 1));

        // Move to the next character
        i++;
    }

    // Use modulo N to ensure the hash value falls within
    // the valid range of hash table bucket indexes (0 to N - 1)
    return sum % N;
}

